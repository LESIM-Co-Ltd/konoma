/// The fallback tile (`pct50`).
const PCT50: &str = "#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#";

/// The 8 x 8 pixel rule of a pattern preset: `[row][column]` is foreground. An unknown preset is
/// the 50 % pattern.
pub(crate) fn pattern_pixels(preset: &str) -> [[bool; 8]; 8] {
    let rows = TILES
        .iter()
        .find(|(n, _)| *n == preset)
        .map_or(PCT50, |(_, r)| *r);
    let mut out = [[false; 8]; 8];
    for (y, row) in rows.split('/').take(8).enumerate() {
        for (x, c) in row.bytes().take(8).enumerate() {
            out[y][x] = c == b'#';
        }
    }
    out
}

/// The names of all presets.
#[cfg(test)]
pub(crate) fn names() -> impl Iterator<Item = &'static str> {
    TILES.iter().map(|(n, _)| *n)
}
